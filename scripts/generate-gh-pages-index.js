// Builds dist/index.html as a static, standalone page combining all 3 already-built widgets
// (Hero, Stats strip, Global trade snapshot) — this is what gh-pages serves at the project
// root. It deliberately does NOT go through Vite's HTML/entry pipeline: adding index.html as
// a 4th Rollup input was tried and rejected because Rollup renamed and content-hashed the 3
// real entry chunks to match index.html's own script tags instead of reusing the existing
// hero.min.js/stats-strip.min.js/global-trade-snapshot.min.js chunks, breaking the stable
// filenames Drupal embeds hardcode. Reading the already-built dist/ output here instead has
// zero risk to those filenames.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { name } = require('../package.json');

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const distDir = path.join(__dirname, '..', 'dist');
const jsFiles = fs.readdirSync(path.join(distDir, 'js'));

const findChunk = prefix => {
  const file = jsFiles.find(f => f.startsWith(`${name}.${prefix}-`) && f.endsWith('.js') && !f.endsWith('.map'));
  if (!file) throw new Error(`generate-gh-pages-index: no built chunk found matching "${name}.${prefix}-*.js" in dist/js`);
  return file;
};

const stylesChunk = findChunk('styles');
const parseTsvChunk = findChunk('ParseTsv');

const html = `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no" />
    <link rel="icon" href="./favicon.png" />
    <link rel="stylesheet" href="./assets/font/fonts.css" />
    <title>${name}</title>
    <style>
      html,
      body {
        margin: 0;
        padding: 0;
      }
      .drupal_placeholder {
        background: repeating-linear-gradient(45deg, #f4f4f4, #f4f4f4 10px, #eaeaea 10px, #eaeaea 20px);
        border-bottom: 1px dashed #999;
        border-top: 1px dashed #999;
        box-sizing: border-box;
        color: #555;
        font: 13px/1.4 -apple-system, BlinkMacSystemFont, sans-serif;
        padding: 24px 20px;
        text-align: center;
      }
    </style>
  </head>
  <body>
    <!--
      gh-pages landing page: combines all 3 embeddable entries (Hero, Stats strip, Global
      trade snapshot) with stand-in blocks where Drupal's own View blocks sit on the real
      unctad.org page. Generated by scripts/generate-gh-pages-index.js from the same built
      output storage.unctad.org's Drupal embeds use — see the README's "Embedding" section
      for the individual snippets.
    -->

    <script type="module" crossorigin src="./js/${name}.hero.min.js"></script>
    <link rel="modulepreload" crossorigin href="./js/${stylesChunk}">
    <link rel="stylesheet" crossorigin href="./css/${name}_styles.min.css">
    <link rel="stylesheet" crossorigin href="./css/${name}_hero.min.css">
    <div class="app-root-${name}" id="app-root-${name}-hero">Loading...</div>

    <div class="drupal_placeholder current-issue">Drupal: "current issue" latest-publication teaser block (cover + title + description + its own buttons)</div>

    <script type="module" crossorigin src="./js/${name}.stats-strip.min.js"></script>
    <link rel="modulepreload" crossorigin href="./js/${parseTsvChunk}">
    <link rel="stylesheet" crossorigin href="./css/${name}_stats_strip.min.css">
    <div class="app-root-${name}" id="app-root-${name}-stats-strip">Loading...</div>

    <div class="drupal_placeholder policy-insights">Drupal: latest "Monthly policy insights" edition block</div>

    <script type="module" crossorigin src="./js/${name}.global-trade-snapshot.min.js"></script>
    <link rel="stylesheet" crossorigin href="./css/${name}_global_trade_snapshot.min.css">
    <div class="app-root-${name}" id="app-root-${name}-global-trade-snapshot">Loading...</div>

    <div class="drupal_placeholder publications_container">Drupal: Publications block</div>
    <div class="drupal_placeholder news_container">Drupal: News block</div>
    <div class="drupal_placeholder videos_container">Drupal: Video block</div>
    <div class="drupal_placeholder">Drupal: Newsletter signup (out of scope)</div>
    <noscript>Your browser does not support Javascript!</noscript>
  </body>
</html>
`;

fs.writeFileSync(path.join(distDir, 'index.html'), html);
console.log(`generate-gh-pages-index: wrote dist/index.html (styles chunk: ${stylesChunk}, ParseTsv chunk: ${parseTsvChunk})`);
